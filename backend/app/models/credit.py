"""Database model for POS reconciliation credits."""

from __future__ import annotations

import uuid
from datetime import datetime
from decimal import Decimal

from sqlalchemy import (
    Boolean,
    CheckConstraint,
    DateTime,
    Index,
    Numeric,
    String,
    UniqueConstraint,
    func,
)
from sqlalchemy.orm import Mapped, mapped_column

from app.database import Base


class Credit(Base):
    """One POS sale unit available for visual reconciliation.

    Each paid POS unit creates one credit.
    A credit can be consumed by at most one visual unit.
    Complimentary items priced at zero are valid credits.
    """

    __tablename__ = "credits"

    __table_args__ = (
        UniqueConstraint(
            "site_id",
            "sale_id",
            "unit_index",
            name="uq_credits_site_sale_unit",
        ),
        CheckConstraint(
            "unit_index > 0",
            name="ck_credits_unit_index_positive",
        ),
        CheckConstraint(
            "unit_price >= 0",
            name="ck_credits_unit_price_non_negative",
        ),
        Index(
            "ix_credits_site_category_timestamp",
            "site_id",
            "category",
            "timestamp",
        ),
        Index(
            "ix_credits_site_sale",
            "site_id",
            "sale_id",
        ),
        Index(
            "ix_credits_available",
            "site_id",
            "category",
            "is_active",
            "consumed_at",
        ),
        Index(
            "ix_credits_detection",
            "consumed_by_detection_event_id",
        ),
    )

    # Stable credit identifier.
    # It can use the deterministic UUID generated by engine/credits.py.
    id: Mapped[str] = mapped_column(
        String(36),
        primary_key=True,
    )

    # POS information
    site_id: Mapped[str] = mapped_column(
        String(64),
        nullable=False,
    )

    # Corresponds to SaleRecord.external_id.
    # A POS sale can generate several credits.
    sale_id: Mapped[str] = mapped_column(
        String(128),
        nullable=False,
    )

    # Position of this unit inside the original POS sale quantity.
    # Starts at 1.
    unit_index: Mapped[int] = mapped_column(
        nullable=False,
    )

    # Original POS sale event timestamp, normalized to UTC
    # by the application before persistence.
    timestamp: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
    )

    # Normalized category used by the reconciliation engine.
    # Examples: coffee, soft_drink.
    category: Mapped[str] = mapped_column(
        String(64),
        nullable=False,
    )

    # Decimal is mandatory: never use float for monetary values.
    # A value of 0.00 is valid for complimentary items.
    unit_price: Mapped[Decimal] = mapped_column(
        Numeric(12, 2),
        nullable=False,
    )

    # Credit lifecycle
    # Inactive credits cannot be used for reconciliation.
    is_active: Mapped[bool] = mapped_column(
        Boolean,
        nullable=False,
        default=True,
        server_default="true",
    )

    # Detection event that consumed this credit.
    # No foreign key yet because the Detection model is not implemented.
    consumed_by_detection_event_id: Mapped[str | None] = mapped_column(
        String(128),
        nullable=True,
    )

    consumed_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True),
        nullable=True,
    )

    # Used when a POS sale is voided or refunded after synchronization.
    deactivated_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True),
        nullable=True,
    )

    deactivation_reason: Mapped[str | None] = mapped_column(
        String(64),
        nullable=True,
    )

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
    )

    @property
    def is_available(self) -> bool:
        """Whether this credit can still be consumed."""
        return (
            self.is_active
            and self.consumed_by_detection_event_id is None
        )

    def __repr__(self) -> str:
        return (
            f"<Credit("
            f"id={self.id!r}, "
            f"site_id={self.site_id!r}, "
            f"sale_id={self.sale_id!r}, "
            f"unit_index={self.unit_index}, "
            f"category={self.category!r}, "
            f"unit_price={self.unit_price}, "
            f"is_active={self.is_active}"
            f")>"
        )
